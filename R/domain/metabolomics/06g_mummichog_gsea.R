# The one fgsea build the parity fixture was generated on, and therefore the
# only one this engine is known to reproduce. See .mmc_gsea_check_fgsea().
.MMC_GSEA_VALIDATED_FGSEA <- "1.36.2"

#' Decide whether the installed fgsea may be used, and how it is reported
#'
#' The engine calls fgsea INTERNALS (`calcGseaStatCumulativeBatch`), whose
#' behaviour is not covered by any stability promise, so "a recent enough
#' fgsea" is not evidence of numerical parity — the exact build is. The parity
#' fixture refuses to establish parity across `x.y` series for that reason, and
#' this is the matching runtime rule, so the engine cannot quietly compute
#' statistics on a build the test suite would decline to validate:
#'
#' \describe{
#'   \item{exactly the validated build}{supported, silent.}
#'   \item{another patch of the same `x.y`}{allowed, with a warning, and the
#'     exact version recorded in the result's `deviations`.}
#'   \item{a different `x.y` series}{refused.}
#' }
#'
#' Centralised here and called from one place per entry point, so the policy
#' cannot drift between the gate and the provenance it reports.
#'
#' @param warn Emit the patch-mismatch warning (the caller that records the
#'   deviation passes FALSE, so one run warns once).
#' @return `NULL` when the build is the validated one, otherwise a single
#'   deviation string. Errors on a different `x.y` series.
#' @noRd
.mmc_gsea_check_fgsea <- function(warn = TRUE) {
  installed <- as.character(utils::packageVersion("fgsea"))
  if (identical(installed, .MMC_GSEA_VALIDATED_FGSEA)) return(NULL)

  series <- function(v) paste(strsplit(v, ".", fixed = TRUE)[[1]][1:2],
                              collapse = ".")
  if (!identical(series(installed), series(.MMC_GSEA_VALIDATED_FGSEA))) {
    .mmc_stop(
      "fgsea ", installed, " is outside the validated compatibility range. ",
      "This engine reproduces ", .MMC_GSEA_REF_REPO, "@",
      substr(.MMC_GSEA_REF_COMMIT, 1, 10), " through fgsea internals that are ",
      "not covered by any API stability promise, and parity was established ",
      "only on fgsea ", .MMC_GSEA_VALIDATED_FGSEA, ". Install that build ",
      "(it is the one renv.lock pins) rather than running the engine on a ",
      "series whose permutation tallies, p-values and NES have not been ",
      "checked against the reference."
    )
  }
  note <- sprintf(paste0("fgsea %s, not the validated %s — same series, so the ",
                         "internals this engine calls are very likely ",
                         "unchanged, but parity was not established on it"),
                  installed, .MMC_GSEA_VALIDATED_FGSEA)
  if (isTRUE(warn)) warning("mummichog GSEA: ", note, call. = FALSE)
  note
}

#' Refuse any gseaParam but 1
#'
#' The pinned reference weights the OBSERVED enrichment score and its NULL
#' DISTRIBUTION differently whenever `gseaParam != 1`. In
#' `util_fgsea.R::.run_fgsea_inner()` the score vector is transformed once with
#' `stats <- abs(stats)^gseaParam`, and then
#'
#' \itemize{
#'   \item the observed score is taken with
#'     `calcGseaStat(..., gseaParam = gseaParam)` — so the selected weights are
#'     raised to the exponent a SECOND time, and
#'   \item every permutation path hardcodes `gseaParam = 1`
#'     (`calcGseaStatCumulativeBatch(..., gseaParam = 1)`, and the single-pathway
#'     `calcGseaStat(..., gseaParam = 1)` loop).
#' }
#'
#' Observed and permuted scores then come from different weightings, so the NES
#' and the permutation p-value are not comparable quantities. That is upstream's
#' behaviour, not a transcription error here, and it is invisible at the default
#' because `x^1` applied twice is still `x`.
#'
#' Rather than silently reproducing invalid statistics, or diverging from the
#' reference by passing 1 (which would make our ES differ from MetaboAnalyst's
#' for the same input), the engine runs only where the two agree.
#'
#' Validate this engine's whole-number settings
#'
#' `n_perm`, `seed`, `min_size` and `max_size` are all used as whole numbers --
#' the batch split needs an integer count, `withr::with_seed()` coerces to
#' integer, and the size filter compares against integer set sizes. They share
#' one validator, `.mmc_as_seed()` from the pinned mummichog stage, which
#' already enforces exactly the right rule and says why in its own docstring:
#' checked BEFORE any coercion, because `as.integer()` turns 1.5 into 1 and
#' "7" into 7 without a word, and the run would then claim a value it was never
#' given. It also bounds the range at `.Machine$integer.max`, past which
#' `as.integer()` yields `NA` and the failure surfaces later under an unrelated
#' message.
#'
#' Only `max_size` needs anything more, because `Inf` is its reference default
#' and a legitimate value. Hence this one wrapper rather than a second
#' validator: everything else calls `.mmc_as_seed()` directly.
#'
#' @param x The supplied upper bound.
#' @return `Inf`, or `x` as an integer; an error otherwise.
#' @noRd
.mmc_gsea_check_max_size <- function(x) {
  if (length(x) == 1L && is.numeric(x) && !is.na(x) && is.infinite(x) && x > 0) {
    return(Inf)
  }
  .mmc_as_seed(x, "max_size")
}

#' @param gsea_param The requested exponent.
#' @return `invisible(TRUE)`, or an error.
#' @noRd
.mmc_gsea_check_param <- function(gsea_param) {
  # Type first, value second. Comparing as.numeric(gsea_param) would admit the
  # quoted "1" and logical TRUE: the first then fails inside `abs(stats)^"1"`,
  # where run_mummichog_gsea()'s tryCatch turns a caller error into "GSEA not
  # applicable", and the second runs as 1 but is stored as TRUE in params.
  ok <- length(gsea_param) == 1L && is.numeric(gsea_param) &&
    !is.na(gsea_param) && is.finite(gsea_param) && gsea_param == 1
  if (!ok) {
    .mmc_stop(
      "gsea_param must be the number 1; got ",
      paste(format(gsea_param), collapse = ", "),
      " (", class(gsea_param)[1], "). The pinned ",
      "MetaboAnalystR engine (", .MMC_GSEA_REF_REPO, "@",
      substr(.MMC_GSEA_REF_COMMIT, 1, 10), ") applies the exponent twice to ",
      "the observed enrichment score while hardcoding 1 in every permutation ",
      "path, so for any other value the NES and the permutation p-value are ",
      "computed against a null distribution with a different weighting and do ",
      "not mean what they say. Reproducing that silently would be wrong, and ",
      "correcting it here would stop matching the reference implementation ",
      "this engine exists to reproduce."
    )
  }
  invisible(TRUE)
}


# ==== ranking statistic =====================================================

# What the metabolomics DE stage puts in its generic `statistic` column, per
# method (R/domain/metabolomics/03_differential.R):
#
#   limma                      topTable()$t              signed moderated t
#   t_test / t_test_equal      t.test()$statistic        signed t
#   wilcoxon                   wilcox.test()$statistic   UNSIGNED rank-sum W
#   precomputed                dropped by the loader     (not available)
#
# One column name, different quantities. A signed ranking is the whole premise
# of GSEA, so the column may only be used when the method that produced it is
# known to put a signed score there. W is non-negative and scales with group
# size: ranking on it would order EmpiricalCompounds by rank-sum magnitude with
# no direction at all, while the report claimed a moderated t.
.MMC_GSEA_SIGNED_STAT_METHODS <- c("limma", "t_test", "t_test_equal")
.MMC_GSEA_UNSIGNED_STAT_METHODS <- c("wilcoxon")

#' Choose and extract the signed GSEA ranking statistic from a DE table
#'
#' The choice is driven by `de_method` (`de_res$method`), never by the column
#' name alone:
#'
#' \describe{
#'   \item{`limma`, `t_test`, `t_test_equal`}{rank on the signed t statistic the
#'     stage stores in `statistic` (a literal `t` column is also accepted).}
#'   \item{`wilcoxon`}{rank on `logFC`. The `statistic` column holds Wilcoxon's
#'     unsigned W, which cannot order a signed ranking; it is never read here.
#'     Without a usable `logFC` the contrast is refused rather than ranked on
#'     something else.}
#'   \item{anything else, including a missing `de_method`}{rank on `logFC`. An
#'     unrecognised method's `statistic` column has unknown provenance, and
#'     guessing is exactly the defect this policy exists to prevent. Refused
#'     when there is no usable `logFC`.}
#' }
#'
#' Every outcome names the column it used and why in `label`, so the choice is
#' reported rather than implied. The ORA input contract is untouched — this
#' function is only ever used for GSEA.
#'
#' @param de_table One contrast's DE table (needs `feature_id` and at least one
#'   of `statistic` / `t` / `logFC`).
#' @param de_method The DE method that produced it (`de_res$method`), or NULL
#'   when it is not known.
#' @return A list with `values` (named numeric vector, keyed by `feature_id`,
#'   finite values only), `metric` (`"t_statistic"` or `"logFC"`), `label`
#'   (a human-readable provenance string) and `de_method` (echoed back).
#'   `NULL` when nothing usable is available under the policy above.
mmc_gsea_rank_metric <- function(de_table, de_method = NULL) {
  if (is.null(de_table) || !is.data.frame(de_table) || nrow(de_table) == 0 ||
      !"feature_id" %in% names(de_table)) {
    return(NULL)
  }
  # Type BEFORE value, and resolved in ONE place so the gate and the extraction
  # cannot disagree about what a column holds. as.numeric() on a factor returns
  # LEVEL CODES, not the labels: a factor `statistic` holding -6 and 4 would
  # pass the gate as 1 and 2 and then be reported as the signed statistic that
  # ranked the experiment. A column that is not numeric is not a statistic, and
  # the caller falls through to logFC with a label saying so.
  column_values <- function(col) {
    if (is.null(col) || !col %in% names(de_table)) return(NULL)
    v <- de_table[[col]]
    if (!is.numeric(v)) return(NULL)
    as.numeric(v)
  }
  usable <- function(col) {
    v <- column_values(col)
    !is.null(v) && any(is.finite(v))
  }
  # NULL, NA and "" all mean "not recorded", and are handled as such rather
  # than reaching the method lookup as a value.
  method <- if (length(de_method) == 0) NA_character_ else
    as.character(de_method)[1]
  if (is.na(method) || !nzchar(method)) method <- NA_character_
  signed_stat <- !is.na(method) && method %in% .MMC_GSEA_SIGNED_STAT_METHODS

  stat_col <- NULL
  if (signed_stat) {
    # Test the candidates in order of preference rather than committing to the
    # first one that merely exists. A DE table can carry an unusable `statistic`
    # (all NA, or non-numeric) next to a perfectly good `t`; picking by name
    # alone would skip the real statistic and rank on logFC instead.
    cand     <- c("statistic", "t")
    stat_col <- Find(usable, cand[cand %in% names(de_table)])
  }

  if (!is.null(stat_col)) {
    v      <- column_values(stat_col)
    metric <- "t_statistic"
    label  <- sprintf("signed t statistic (DE method '%s', column '%s')",
                      method, stat_col)
  } else if (usable("logFC")) {
    v      <- column_values("logFC")
    metric <- "logFC"
    label  <- if (!is.na(method) && method %in% .MMC_GSEA_UNSIGNED_STAT_METHODS) {
      sprintf(paste0("log2 fold change (DE method '%s' reports an unsigned ",
                     "rank-sum statistic, which cannot order a signed ranking)"),
              method)
    } else if (signed_stat) {
      sprintf("log2 fold change (DE method '%s' left no usable t statistic)",
              method)
    } else if (is.na(method)) {
      paste0("log2 fold change (the DE method was not recorded, so the ",
             "'statistic' column was not trusted to be signed)")
    } else {
      sprintf(paste0("log2 fold change (DE method '%s' is not known to report ",
                     "a signed statistic)"), method)
    }
  } else {
    return(NULL)
  }

  keep <- is.finite(v)
  if (!any(keep)) return(NULL)
  list(
    values    = stats::setNames(v[keep], as.character(de_table$feature_id)[keep]),
    metric    = metric,
    label     = label,
    de_method = method
  )
}


# ==== EmpiricalCompound scores ==============================================

#' Build the EmpiricalCompound score vector
#'
#' Two steps, and they do NOT have the same standing:
#'
#' \enumerate{
#'   \item features that share the same m/z are merged with `rank_metric`
#'     (default `"mean"`) — **our implementation choice**, see below;
#'   \item each EmpiricalCompound takes the **signed maximum** of its member
#'     features' merged scores — this one is upstream's rule,
#'     `ec.exp.vec <- unlist(lapply(ec_exp_dict, max))`: no mean, no
#'     `max(abs())`, no "most significant feature", and no direction invented
#'     at the EC level.
#' }
#'
#' @section Step 1 is not established as upstream-equivalent:
#' Reading `peaks_to_function.R` at the pinned commit, `rank.metric` is used
#' only inside the **meta-analysis** function `.search.compoundLibMeta`, where
#' it collapses one row's `";"`-joined `Matched.Scores`. The single-dataset path
#' this engine's stage runs drops duplicate m/z rows earlier
#' (`SanityCheckMummichogData`: `dup.inx <- duplicated(ndat[[mz.col]])`), so by
#' the time scores exist each m/z carries exactly one, and no merge happens at
#' all. `.compute.mummichog.RT.fgsea`, the function reproduced in
#' `mmc_gsea_metaboanalyst()`, never sees `rank.metric`.
#'
#' Step 1 is therefore documented as what it is — a choice made here for inputs
#' where several features share an m/z — and not as reproduced behaviour. Two
#' consequences worth knowing before reading an EC score:
#'
#' \itemize{
#'   \item `read_mummichog_ec_features()` yields one row per (EC, feature), so a
#'     feature mapped to several EmpiricalCompounds contributes several rows to
#'     the m/z group. With `"mean"`, such a feature is weighted by its
#'     feature-EC multiplicity rather than counted once.
#'   \item whether either behaviour matches the reference end to end is
#'     **unverified**: the parity fixture contains no feature in more than one
#'     EC and no two features sharing an m/z.
#' }
#'
#' The GSEA calculation downstream of this vector IS checked against upstream —
#' see `mmc_gsea_metaboanalyst()`. That parity starts from the ranked EC inputs;
#' it says nothing about how they were built.
#'
#' @param ec_features  Per-(EC, feature) frame from `read_mummichog_ec_features()`
#'   (needs `EID`, `feature_id`, `mz`).
#' @param feature_scores Named numeric vector of per-feature ranking statistics,
#'   keyed by `feature_id` (from `mmc_gsea_rank_metric()$values`).
#' @param rank_metric  How to merge features sharing one m/z: `"mean"`
#'   (default), `"min"`, `"max"` or `"median"`.
#' @return A named numeric vector of EC scores, sorted decreasing; empty named
#'   numeric when nothing can be scored.
mmc_ec_scores <- function(ec_features, feature_scores,
                          rank_metric = .MMC_GSEA_RANK_METRICS) {
  rank_metric <- match.arg(rank_metric, .MMC_GSEA_RANK_METRICS)
  out <- stats::setNames(numeric(0), character(0))
  if (is.null(ec_features) || !is.data.frame(ec_features) ||
      nrow(ec_features) == 0 || length(feature_scores) == 0) {
    return(out)
  }
  score <- unname(feature_scores[as.character(ec_features$feature_id)])
  # Keyed on the m/z string mummichog echoed back, so the grouping matches its
  # own notion of "the same m/z" without float-equality surprises. A missing m/z
  # becomes its own group rather than being dropped by the formula interface.
  mz <- as.character(ec_features$mz)
  na_mz <- is.na(mz)
  if (any(na_mz)) mz[na_mz] <- paste0("<na>", which(na_mz))

  df <- data.frame(
    EID   = as.character(ec_features$EID),
    mz    = mz,
    score = score,
    stringsAsFactors = FALSE
  )
  df <- df[is.finite(df$score) & !is.na(df$EID), , drop = FALSE]
  if (nrow(df) == 0) return(out)

  # -- step 1: merge scores of features sharing one m/z ----------------------
  agg <- switch(rank_metric,
                mean   = mean,
                min    = min,
                max    = max,
                median = stats::median)
  merged <- stats::aggregate(score ~ mz, data = df, FUN = agg)
  df$score <- merged$score[match(df$mz, merged$mz)]

  # -- step 2: EC score = signed max over its member features ---------------
  # Distinct (EC, m/z) pairs only: an m/z matching the same EC through several
  # candidate compounds must not weight the max differently.
  uniq <- unique(df[, c("EID", "mz", "score")])
  ec   <- stats::aggregate(score ~ EID, data = uniq, FUN = max)
  sort(stats::setNames(ec$score, ec$EID), decreasing = TRUE)
}

#' Build pathway gene-set equivalents: pathway -> detected EmpiricalCompounds
#'
#' An EmpiricalCompound belongs to a pathway when ANY of its candidate compounds
#' is a compound of that pathway — the same relation MetaboAnalyst holds as
#' `mSetObj$pathways$emp_cpds`. Only ECs present in `ec_ids` (the ranked
#' universe) are kept, so set sizes describe what was actually detected.
#'
#' @param model_pathways Named list: pathway -> compound ids (from
#'   `read_mummichog_model_pathways()$pathways`).
#' @param ec_candidates  Long EC -> candidate frame from
#'   `read_mummichog_ec_candidates()`.
#' @param ec_ids         Character vector of ECs in the ranked universe.
#' @return Named list: pathway -> character vector of detected EC ids. Pathways
#'   with no detected EC are dropped.
mmc_pathway_ec_sets <- function(model_pathways, ec_candidates, ec_ids) {
  if (length(model_pathways) == 0 || is.null(ec_candidates) ||
      nrow(ec_candidates) == 0 || length(ec_ids) == 0) {
    return(list())
  }
  cand <- ec_candidates[ec_candidates$EID %in% ec_ids, , drop = FALSE]
  if (nrow(cand) == 0) return(list())
  # compound id -> ECs that carry it as a candidate
  cpd_to_ec <- split(cand$EID, cand$compound_id)

  sets <- lapply(model_pathways, function(cpds) {
    hits <- cpd_to_ec[intersect(cpds, names(cpd_to_ec))]
    unique(unlist(hits, use.names = FALSE))
  })
  sets[vapply(sets, length, integer(1)) > 0L]
}


# ==== upstream ranked-input construction ====================================

#' Build the two ranked vectors MetaboAnalyst's GSEA engine consumes
#'
#' Reproduces the construction in the pinned
#' `peaks_to_function.R::.compute.mummichog.RT.fgsea()` (lines 3470-3483)
#' verbatim in behaviour:
#'
#' \preformatted{
#' df.scores  <- data.frame(id = names(total_ecpds), scores = total_ecpds)
#' ag.scores  <- aggregate(id ~ scores, data = df.scores, paste, collapse = "; ")
#' ag.sorted  <- ag.scores[order(-ag.scores$scores), ]
#' dt.scores.out <- <one row per EC, carrying its tie-group row index>
#' rank.vec   <- tie-group index, named by EC id
#' scores.vec <- unique signed scores, named by the ";"-joined EC ids
#' }
#'
#' So ECs that share a score are COLLAPSED into one ranked position whose name
#' is the `"; "`-joined list of their ids, and `ranks` maps every individual EC
#' to that position's index. Both vectors are ordered by descending SIGNED
#' score. This is what makes the engine's index semantics non-trivial, and it is
#' why the ranked vector is shorter than the EC universe whenever scores tie.
#'
#' @param ec_scores Named numeric vector of signed EC scores (from
#'   `mmc_ec_scores()`).
#' @return A list with `stats` (unique signed scores, descending, named by the
#'   `"; "`-joined EC ids) and `ranks` (per-EC tie-group index, named by EC id).
#'   Both empty when `ec_scores` is empty.
mmc_gsea_ranked_inputs <- function(ec_scores) {
  empty <- list(stats = stats::setNames(numeric(0), character(0)),
                ranks = stats::setNames(numeric(0), character(0)))
  if (length(ec_scores) == 0 || is.null(names(ec_scores))) return(empty)
  keep <- is.finite(ec_scores) & nzchar(names(ec_scores))
  ec_scores <- ec_scores[keep]
  if (length(ec_scores) == 0) return(empty)

  df <- data.frame(id = names(ec_scores), scores = unname(ec_scores),
                   stringsAsFactors = FALSE)
  ag <- stats::aggregate(id ~ scores, data = df, paste, collapse = "; ")
  ag <- ag[order(-ag$scores), , drop = FALSE]
  rownames(ag) <- NULL

  stats_vec <- stats::setNames(as.numeric(ag$scores), as.character(ag$id))

  # Expand each tie group back to its member ECs, carrying the group's index —
  # upstream's data.table `by = 1:nrow(dt.scores)` idiom.
  idx  <- lapply(seq_len(nrow(ag)),
                 function(i) strsplit(as.character(ag$id[i]), "; ",
                                      fixed = TRUE)[[1]])
  ranks_vec <- stats::setNames(
    as.numeric(rep(seq_len(nrow(ag)), vapply(idx, length, integer(1)))),
    unlist(idx, use.names = FALSE)
  )
  list(stats = stats_vec, ranks = ranks_vec)
}


# ==== MetaboAnalyst-equivalent GSEA engine ==================================

#' Run MetaboAnalystR's vendored fixed-permutation GSEA
#'
#' A line-for-line reproduction of the pinned
#' `util_fgsea.R::.run_fgsea_inner()` (see the file header for why no public
#' fgsea entry point can stand in for it). The enrichment score and the
#' permutation batch come from fgsea's own primitives, called exactly as
#' upstream calls them:
#'
#' \itemize{
#'   \item `stats <- abs(stats)^gseaParam`, then — on fgsea > 1.24.0, which is
#'     the branch upstream takes for any modern fgsea —
#'     `stats <- sort(stats, decreasing = TRUE)`. `abs()` BEFORE the sort is
#'     what makes the ranking a |score| ranking, and the re-sort happens AFTER
#'     the pathway positions were derived from the signed ordering, which is why
#'     ES/NES sign carries no interpretable direction (see
#'     `mmc_gsea_nes_note()`).
#'   \item pathway members become tie-group indices via
#'     `ranks[na.omit(fmatch(members, names(ranks)))]`, NOT de-duplicated, so
#'     two ECs in one tie group count twice toward `size` and the ES.
#'   \item `fgsea::calcGseaStat(..., returnLeadingEdge = TRUE)` for ES.
#'   \item `fgsea:::calcGseaStatCumulativeBatch(..., seed = seeds[i],
#'     scoreType = "std")` for the permutation tallies. The single-pathway case
#'     uses upstream's plain `sample.int()` loop, but SEEDED: upstream leaves it
#'     to the BiocParallel worker's RNG, which is not seed-deterministic, so
#'     there is no reference draw to reproduce. That branch is therefore the one
#'     place this engine does not claim numerical parity — it is reproducible
#'     instead, the parity fixture does not exercise it, and
#'     `run_mummichog_gsea()` records it in `deviations`.
#'   \item a pathway with no valid draw is TESTED but not PERMUTED — either its
#'     tie-expanded size exceeds the ranking, or it is the sole permutable
#'     pathway and covers every position. Its null is all zeros, mirroring the
#'     ES = 0 its observed score necessarily took, which gives `p = 1` exactly.
#'     Upstream aborts on both shapes instead, so this is a deliberate
#'     departure; it is counted in `"mmc_unpermutable"` and reported in
#'     `deviations`, and it applies only to inputs on which the reference
#'     produces no result at all.
#'   \item `pval = min((1+leEs)/(1+leZero), (1+geEs)/(1+geZero))`,
#'     `NES = ES / mean(same-sign permuted ES)`,
#'     `padj = p.adjust(pval, "fdr")` over the kept pathways only.
#'   \item leading edge = `names(stats)[le]` split on `"; "`, intersected with
#'     the pathway's own EC ids.
#' }
#'
#' @section What the ES = 0 fallback propagates into:
#' A pathway that takes upstream's fallback does not merely lose its ES — the
#' zero flows through every downstream quantity, and the arithmetic makes two of
#' them exact rather than incidental:
#'
#' \itemize{
#'   \item **NES = 0.** `NES = ES / mean(same-sign permuted ES)`, so a zero
#'     numerator gives zero for any finite non-zero mean (and `NaN` in the
#'     degenerate case where no permuted score falls on that side).
#'   \item **p = 1 exactly.** With `ES = 0`, every permuted score is both `<= 0`
#'     and `>= 0`, so `leEs == leZero` and `geEs == geZero`; both ratios in
#'     `pmin((1+leEs)/(1+leZero), (1+geEs)/(1+geZero))` are exactly 1.
#'   \item **It still consumes a test.** `p.adjust(pval, "fdr")` runs over every
#'     tested pathway, defaulted ones included, so each fallback raises the BH
#'     denominator and the adjusted p-values of the pathways that did score.
#' }
#'
#' None of this is changed here: the point of this function is to reproduce the
#' pinned reference, and the reference behaves this way. It is surfaced instead
#' — `es_defaulted` and `es_reason` mark the affected rows — so a 0 is never
#' read as a measured enrichment, and so the cost to the BH correction is
#' visible to whoever interprets the table.
#'
#' @param pathways Named list: pathway -> character vector of EC ids.
#' @param stats    Ranked score vector from `mmc_gsea_ranked_inputs()$stats`.
#' @param ranks    Per-EC tie-group index from `mmc_gsea_ranked_inputs()$ranks`.
#' @param n_perm   Permutations (upstream default 100).
#' @param min_size,max_size Size bounds on the tie-group index vector
#'   (upstream defaults 1 and `Inf`).
#' @param gsea_param Enrichment-score weight exponent (upstream default 1).
#' @param seed     Seed for the permutation batch seeds (upstream `set.seed(123)`).
#' @return A data.frame with one row per TESTED pathway: `pathway`, `pval`,
#'   `padj`, `ES`, `NES`, `nMoreExtreme`, `size`, `leadingEdge` (`"; "`-joined
#'   EC ids), `es_defaulted` (TRUE when upstream's tryCatch fallback supplied
#'   `ES = 0` instead of a computed score) and `es_reason` (why, from
#'   `.mmc_gsea_fallback_reason()`; `NA` when the score was computed). Zero rows
#'   when no pathway passes the size filter. A non-empty result carries the
#'   `"mmc_single_pathway_rng"` attribute, `TRUE` when the seeded single-pathway
#'   loop ran instead of the batch, and `"mmc_unpermutable"`, the number of
#'   pathways tested without being permuted — the engine reports both so a
#'   consumer does not have to infer them from the row count or the sizes.
mmc_gsea_metaboanalyst <- function(pathways, stats, ranks,
                                   n_perm     = .MMC_GSEA_DEFAULTS$n_perm,
                                   min_size   = .MMC_GSEA_DEFAULTS$min_size,
                                   max_size   = .MMC_GSEA_DEFAULTS$max_size,
                                   gsea_param = .MMC_GSEA_DEFAULTS$gsea_param,
                                   seed       = .MMC_GSEA_DEFAULTS$seed) {
  # Ahead of every other check: an unusable exponent is a caller error, not a
  # property of the inputs, and must not be masked by an empty-input return or
  # by a missing package.
  .mmc_gsea_check_param(gsea_param)
  # Validated, not coerced, and before anything uses them. An invalid size
  # bound is the worst of these: NA on either side makes the filter predicate
  # all-NA, which() returns nothing, and the run reports "no pathway passed"
  # -- a valid experiment vanishing as a plausible empty result.
  n_perm   <- .mmc_as_seed(n_perm, "n_perm")
  seed     <- .mmc_as_seed(seed, "seed")
  min_size <- .mmc_as_seed(min_size, "min_size")
  max_size <- .mmc_gsea_check_max_size(max_size)
  if (n_perm < 1L) .mmc_stop("n_perm must be at least 1; got ", n_perm, ".")

  # Every column the populated result carries, including the two diagnostics:
  # a caller that rbinds runs together, or reads the documented schema, must
  # not find the contract narrower on a valid empty run.
  empty <- data.frame(pathway = character(0), pval = numeric(0),
                      padj = numeric(0), ES = numeric(0), NES = numeric(0),
                      nMoreExtreme = numeric(0), size = numeric(0),
                      leadingEdge = character(0), es_defaulted = logical(0),
                      es_reason = character(0), stringsAsFactors = FALSE)
  if (length(pathways) == 0 || length(stats) == 0 || length(ranks) == 0) {
    return(empty)
  }
  for (pkg in c("fgsea", "fastmatch", "data.table", "BiocParallel")) {
    if (!requireNamespace(pkg, quietly = TRUE)) {
      .mmc_stop("package '", pkg, "' is required for the MetaboAnalyst-style ",
                "GSEA engine.")
    }
  }
  # Before any statistic is computed: an unvalidated fgsea must not produce
  # numbers at all, rather than produce them and be caveated afterwards.
  .mmc_gsea_check_fgsea()

  # -- permutation batching + batch seeds (upstream, verbatim) ---------------
  granularity <- .MMC_GSEA_GRANULARITY
  perm_per_proc <- rep(granularity, floor(n_perm / granularity))
  if (n_perm - sum(perm_per_proc) > 0) {
    perm_per_proc <- c(perm_per_proc, n_perm - sum(perm_per_proc))
  }
  if (length(perm_per_proc) == 0) {
    .mmc_stop("n_perm must be >= 1; got ", n_perm, ".")
  }
  withr::with_seed(seed, {
    batch_seeds <- sample.int(10^9, length(perm_per_proc))
  })

  min_size <- max(min_size, 1L)
  # abs() BEFORE any sorting: this is the step that turns the ranking into a
  # |score| ranking and is why NES sign is not a biological direction.
  stats <- abs(stats)^gsea_param

  # -- pathway members -> tie-group indices (no de-duplication) -------------
  pathways_pos <- lapply(pathways, function(p) {
    as.vector(stats::na.omit(fastmatch::fmatch(as.character(p), names(ranks))))
  })
  pathways_filtered <- lapply(pathways_pos, function(s) ranks[s])
  pathways_sizes <- vapply(pathways_filtered, length, integer(1))

  to_keep <- which(min_size <= pathways_sizes & pathways_sizes <= max_size)
  m <- length(to_keep)
  if (m == 0) return(empty)
  pathways_filtered <- pathways_filtered[to_keep]
  pathways_sizes    <- pathways_sizes[to_keep]

  # A pathway whose tie-expanded size exceeds the ranking cannot be permuted at
  # all: no draw of that many distinct positions exists. BOTH permutation paths
  # would abort on it — `sample.int()` in the single-pathway loop, fgsea's C++
  # batch in the multi-pathway one — so the condition is recognised once here,
  # ahead of either, rather than guarded separately inside each.
  #
  # Only ties can produce it: a size above the ranking means the tie-group index
  # vector repeats a position, which is exactly what `calcGseaStat`'s
  # strictly-increasing assertion rejects. Such a pathway's observed score has
  # therefore already taken the ES = 0 fallback, and the null below mirrors it.
  permutable <- which(pathways_sizes <= length(stats))
  # One more pathway gets a substituted null rather than a drawn one, and it
  # has to be counted here rather than hidden inside the loop: a SOLE
  # permutable pathway covering the whole ranking. Every draw returns all
  # positions, which `calcGseaStat()` refuses for the same reason it refused
  # the observed score, so the loop substitutes zero too. Recognising it here
  # keeps one answer to "was this pathway permuted?" and makes the departure
  # countable; the numbers are unchanged either way, since the all-zero null
  # below is exactly what that loop accumulated.
  #
  # It is deliberately NOT applied when two or more pathways are permutable:
  # the batch path CAN draw every position, so an all-position pathway really
  # is permuted there. That asymmetry is upstream's two code paths, not ours.
  if (length(permutable) == 1 &&
      pathways_sizes[permutable] == length(stats)) {
    permutable <- integer(0)
  }

  # -- enrichment scores ----------------------------------------------------
  # fgsea > 1.24.0 is the branch upstream takes (renv.lock pins fgsea 1.36.2, so
  # it is also the only branch this pipeline can reach): it re-sorts the already
  # absolute values descending. Kept because it defines the ranking the
  # reference implementation scores against.
  if (utils::packageVersion("fgsea") > "1.24.0") {
    stats <- sort(stats, decreasing = TRUE)
  }
  # Upstream wraps calcGseaStat in a tryCatch that falls back to
  # `list(res = 0, leadingEdge = c())`. That fallback is not decorative: because
  # tie-group indices are never de-duplicated, a pathway holding two ECs with
  # the SAME score passes a non-strictly-increasing `selectedStats`, and
  # fgsea::calcGseaStat asserts `all(head(S, -1) < tail(S, -1))` — so such a
  # pathway really does come out of the reference implementation with ES = 0,
  # NES = 0 and an empty leading edge.
  #
  # We reproduce that numerically AND record WHY each fallback happened. A
  # blanket "tied scores" label would hide any other calcGseaStat failure behind
  # a plausible-sounding explanation, so the reason is classified from the actual
  # condition (see .mmc_gsea_fallback_reason()) and anything unrecognised is
  # reported verbatim as unexpected.
  gsea_res <- lapply(pathways_filtered, function(selected) {
    if (length(selected) == 0 || any(is.na(selected))) {
      return(list(res = 0, leadingEdge = c(),
                  .mmc_reason = .mmc_gsea_fallback_reason(selected, NULL)))
    }
    tryCatch(
      fgsea::calcGseaStat(stats = stats, selectedStats = selected,
                          gseaParam = gsea_param, returnLeadingEdge = TRUE),
      error = function(e) {
        list(res = 0, leadingEdge = c(),
             .mmc_reason = .mmc_gsea_fallback_reason(selected,
                                                     conditionMessage(e)))
      })
  })
  es_defaulted <- vapply(gsea_res, function(x) !is.null(x$.mmc_reason),
                         logical(1), USE.NAMES = FALSE)
  es_reason <- vapply(gsea_res,
                      function(x) if (is.null(x$.mmc_reason)) NA_character_ else
                        x$.mmc_reason,
                      character(1), USE.NAMES = FALSE)
  unexpected <- es_defaulted & startsWith(es_reason, .MMC_GSEA_FALLBACK_UNEXPECTED)
  if (any(unexpected)) {
    warning("mummichog GSEA: ", sum(unexpected), " pathway(s) hit an ",
            "UNEXPECTED calcGseaStat failure and took the reference ",
            "implementation's ES = 0 fallback: ",
            paste(unique(es_reason[unexpected]), collapse = " | "),
            call. = FALSE)
  }
  pathway_scores <- vapply(gsea_res, function(x) as.numeric(x$res), numeric(1),
                           USE.NAMES = FALSE)
  leading_edges <- lapply(gsea_res, function(x) {
    if (length(x$leadingEdge) == 0) character(0) else names(stats)[x$leadingEdge]
  })

  # -- permutation tallies --------------------------------------------------
  # Every pathway starts from the tally a null of all zeros produces, which is
  # what the seeded loop would accumulate for an unpermutable pathway: each
  # draw scores 0, so it is both `<=` and `>=` the observed score. Paired with
  # the ES = 0 those pathways already carry, that gives p = 1 exactly. Pathways
  # that CAN be permuted then overwrite their own entries.
  tallies <- lapply(seq_along(perm_per_proc), function(i) {
    n1  <- perm_per_proc[i]
    acc <- list(leEs      = n1 * as.numeric(0 <= pathway_scores),
                geEs      = n1 * as.numeric(0 >= pathway_scores),
                leZero    = rep(n1, m), geZero    = rep(n1, m),
                leZeroSum = rep(0, m),  geZeroSum = rep(0, m))
    if (length(permutable) == 0) return(acc)
    sub <- if (length(permutable) == 1) {
      .mmc_gsea_perm_single(stats, pathway_scores[permutable],
                            pathways_sizes[permutable], n1, batch_seeds[i])
    } else {
      .mmc_gsea_perm_batch(stats, pathway_scores[permutable],
                           pathways_sizes[permutable], n1, batch_seeds[i])
    }
    for (f in names(acc)) acc[[f]][permutable] <- as.numeric(sub[[f]])
    acc
  })

  # Sum each tally across batches, per pathway. Identical to upstream for any
  # n_perm <= granularity (1000) — which covers the default 100 — and it is what
  # upstream's row-indexed aggregation intends; see the note in
  # run_mummichog_gsea() for the >1000 case.
  add <- function(field) {
    Reduce(`+`, lapply(tallies, function(t) as.numeric(t[[field]])))
  }
  leEs <- add("leEs"); geEs <- add("geEs")
  leZero <- add("leZero"); geZero <- add("geZero")
  leZeroSum <- add("leZeroSum"); geZeroSum <- add("geZeroSum")

  pval <- pmin((1 + leEs) / (1 + leZero), (1 + geEs) / (1 + geZero))
  le_zero_mean <- leZeroSum / leZero
  ge_zero_mean <- geZeroSum / geZero

  es  <- pathway_scores
  nes <- es / ifelse(es > 0, ge_zero_mean, abs(le_zero_mean))
  n_more_extreme <- ifelse(es > 0, geEs, leEs)

  # BH over exactly the tested pathways.
  padj <- stats::p.adjust(pval, method = "fdr")

  # Leading edge: tie-group names split back to EC ids, then intersected with
  # the pathway's own ECs (upstream's `mapply(intersect, ...)`).
  lead <- vapply(seq_len(m), function(i) {
    le <- unlist(strsplit(leading_edges[[i]], "; ", fixed = TRUE),
                 use.names = FALSE)
    pw <- names(pathways_filtered[[i]])
    hit <- unique(le[le %in% pw])
    if (length(hit) == 0) NA_character_ else paste(hit, collapse = "; ")
  }, character(1))

  out <- data.frame(
    pathway      = names(pathways_filtered),
    pval         = as.numeric(pval),
    padj         = as.numeric(padj),
    ES           = as.numeric(es),
    NES          = as.numeric(nes),
    nMoreExtreme = as.numeric(n_more_extreme),
    size         = as.numeric(pathways_sizes),
    leadingEdge  = lead,
    es_defaulted = es_defaulted,
    es_reason    = es_reason,
    stringsAsFactors = FALSE
  )
  # Which permutation path ran is the engine's to report, not something a
  # consumer should re-derive: the seeded loop is taken when exactly one
  # pathway is PERMUTABLE, which is not the same as one row in the result once
  # unpermutable pathways are also tested. Carried as an attribute so the
  # documented column schema is unchanged.
  attr(out, "mmc_single_pathway_rng") <- length(permutable) == 1
  # Likewise for the pathways that were tested but never permuted: upstream
  # aborts on them, so returning a row at all is ours, and it has to travel
  # with the result rather than be reconstructed from sizes by each consumer.
  attr(out, "mmc_unpermutable") <- m - length(permutable)
  out
}

# Prefix marking a fallback whose cause we do NOT recognise. Anything carrying
# it is surfaced as a warning rather than explained away.
.MMC_GSEA_FALLBACK_UNEXPECTED <- "unexpected calcGseaStat failure: "

#' Classify why the reference implementation's ES = 0 fallback fired
#'
#' Upstream's `tryCatch` swallows every `calcGseaStat` failure into the same
#' `ES = 0` result, so the reason has to be reconstructed. It is classified from
#' the CONDITION, not from a guess:
#'
#' \describe{
#'   \item{tied EC scores}{`selectedStats` holds duplicate ranked positions —
#'     the direct consequence of upstream not de-duplicating tie-group indices,
#'     and what `calcGseaStat`'s strictly-increasing assertion rejects. Detected
#'     on the indices themselves, not on the message text.}
#'   \item{every ranked position selected}{`calcGseaStat` refuses the degenerate
#'     case where the pathway covers the whole ranking.}
#'   \item{empty or missing members}{upstream's own pre-check branch, which
#'     returns the default without calling `calcGseaStat` at all.}
#'   \item{anything else}{reported verbatim behind
#'     `.MMC_GSEA_FALLBACK_UNEXPECTED`, so a genuine bug or a future fgsea change
#'     is visible instead of being mislabelled as a tie.}
#' }
#'
#' @param selected The pathway's ranked-position vector.
#' @param msg      `conditionMessage()` of the caught error, or `NULL` when the
#'   fallback came from upstream's pre-check rather than an error.
#' @return A single character scalar describing the cause.
#' @noRd
.mmc_gsea_fallback_reason <- function(selected, msg) {
  if (is.null(msg)) {
    return(if (length(selected) == 0) "pathway has no ranked members" else
      "pathway members include a missing rank")
  }
  # The tie condition IS duplicated ranked positions; check that directly.
  if (any(duplicated(selected))) {
    n <- sum(duplicated(selected))
    return(sprintf("tied EC scores (%d duplicate ranked position%s)",
                   n, if (n == 1) "" else "s"))
  }
  if (grepl("all genes are selected", msg, fixed = TRUE)) {
    return("pathway selects every ranked position")
  }
  paste0(.MMC_GSEA_FALLBACK_UNEXPECTED, msg)
}

#' Run upstream's single-pathway permutation loop, seeded
#'
#' The branch upstream takes when exactly one pathway is permutable: a plain
#' `sample.int()` loop rather than the cumulative batch. Seeded here so the run
#' is reproducible — upstream leaves it to the BiocParallel worker's RNG, which
#' is not seed-deterministic, so there is no reference draw to match. It is the
#' one place this engine offers reproducibility INSTEAD of numerical parity;
#' `run_mummichog_gsea()` records that as a deviation and the parity fixture
#' never reaches it.
#'
#' Callers now filter out both shapes that have no valid draw — a size above
#' the ranking, and a sole pathway covering all of it — so the guard below is
#' unreachable from `mmc_gsea_metaboanalyst()` and is kept only so a direct
#' caller cannot walk into `sample.int()` asking for more positions than exist,
#' or into the all-selected set `calcGseaStat()` refuses.
#'
#' @param stats,pathway_scores,pathways_sizes,iterations,seed Passed through;
#'   the scores and sizes hold the single permutable pathway.
#' @return A tally list with the same six fields as the batch's.
#' @noRd
.mmc_gsea_perm_single <- function(stats, pathway_scores, pathways_sizes,
                                  iterations, seed) {
  K   <- max(pathways_sizes)
  acc <- list(leEs = 0, geEs = 0, leZero = 0, geZero = 0,
              leZeroSum = 0, geZeroSum = 0)
  withr::with_seed(seed, {
    for (k in seq_len(iterations)) {
      if (K >= length(stats)) {
        rand_es <- 0
      } else {
        draw <- sample.int(length(stats), K)
        # Anything calcGseaStat still refuses on a proper sub-sample scores 0
        # only if it is a cause we recognise; a real failure is re-raised
        # rather than absorbed into the null distribution.
        rand_es <- tryCatch(
          fgsea::calcGseaStat(stats = stats, selectedStats = draw,
                              gseaParam = 1),
          error = function(e) {
            reason <- .mmc_gsea_fallback_reason(draw, conditionMessage(e))
            if (startsWith(reason, .MMC_GSEA_FALLBACK_UNEXPECTED)) stop(e)
            0
          })
      }
      acc$leEs      <- acc$leEs + (rand_es <= pathway_scores)
      acc$geEs      <- acc$geEs + (rand_es >= pathway_scores)
      acc$leZero    <- acc$leZero + (rand_es <= 0)
      acc$geZero    <- acc$geZero + (rand_es >= 0)
      acc$leZeroSum <- acc$leZeroSum + pmin(rand_es, 0)
      acc$geZeroSum <- acc$geZeroSum + pmax(rand_es, 0)
    }
  })
  acc
}

#' Call fgsea's cumulative permutation batch the way upstream does
#'
#' `calcGseaStatCumulativeBatch()` is fgsea-internal (upstream reaches it with
#' `fgsea:::`), and its `scoreType` argument only exists from fgsea > 1.12.0 —
#' upstream branches on exactly that. Isolated here so the one internal call in
#' this file is guarded and explained in one place.
#'
#' @param stats,pathway_scores,pathways_sizes,iterations,seed Passed through.
#' @return The batch's tally list.
#' @noRd
.mmc_gsea_perm_batch <- function(stats, pathway_scores, pathways_sizes,
                                 iterations, seed) {
  fn <- tryCatch(get("calcGseaStatCumulativeBatch",
                     envir = asNamespace("fgsea")),
                 error = function(e) NULL)
  if (is.null(fn)) {
    .mmc_stop("this fgsea build does not expose calcGseaStatCumulativeBatch, ",
              "which the MetaboAnalyst-style GSEA permutation scheme requires.")
  }
  args <- list(stats = stats, gseaParam = 1,
               pathwayScores = pathway_scores,
               pathwaysSizes = pathways_sizes,
               iterations = iterations, seed = seed)
  # Upstream's own branch, kept so this mirrors the pinned source. The
  # compatibility gate in mmc_gsea_metaboanalyst() admits only the validated
  # 1.36.x series, so in this pipeline it always takes the first arm; the
  # comparison stays because it is what upstream writes, not a live choice.
  if (utils::packageVersion("fgsea") > "1.12.0") args$scoreType <- "std"
  do.call(fn, args)
}


# ==== NES interpretation ====================================================

#' The one sanctioned description of NES sign for this analysis
#'
#' Two independent reasons NES sign must not be over-read here:
#'
#'   1. the ranked vector is transformed to |score|
#'      (`stats <- abs(stats)^gseaParam`), so it carries no direction; and
#'   2. pathway positions are built from the SIGNED-score ordering
#'      (`ranks[fmatch(members, names(ranks))]`) BEFORE that transform and the
#'      subsequent magnitude re-sort, so the indices a pathway is scored at no
#'      longer necessarily correspond to where its ECs sit in the transformed
#'      ranking at all.
#'
#' Sign is therefore retained purely for parity with the reference
#' implementation, and is deliberately NOT described as a direction — neither
#' biological up/down, nor a claim about the magnitude of the pathway members'
#' own scores. Kept as a single function so every table, plot, export and
#' report sentence says the same thing, and so the regression test has one
#' place to assert.
#'
#' @return A single character scalar.
mmc_gsea_nes_note <- function() {
  paste0("NES sign is retained to reproduce the pinned MetaboAnalystR result. ",
         "Because the reference implementation transforms and reorders the ",
         "score vector after pathway positions are constructed, NES sign ",
         "should not be interpreted as biological up/down direction or as a ",
         "direct statement about the magnitude of the pathway members' ",
         "original scores.")
}


# ==== the GSEA run ==========================================================

#' Run MetaboAnalyst-style GSEA on the mummichog EmpiricalCompound universe
#'
#' Uses the FULL ranked EC list — no feature significance cutoff — so this is a
#' genuinely different question from the ORA the pinned engine already reported.
#' The engine's own results are read-only inputs here; nothing of the ORA is
#' recomputed or overwritten.
#'
#' Defaults are MetaboAnalyst's (`n_perm = 100`, `gsea_param = 1`,
#' `min_size = 1`, `max_size = Inf`, `seed = 123`). Overriding any of them is a
#' deliberate departure from the reference implementation and is reported back
#' in `deviations`.
#'
#' @param files    One contrast's mummichog output files.
#' @param de_table That contrast's DE table (for the signed ranking statistic).
#' @param model    Model index from `read_mummichog_model_pathways()` /
#'   `mmc_load_model_pathways()`.
#' @param contrast Contrast label, carried through as provenance only — it is
#'   deliberately NOT used to interpret NES sign.
#' @param de_method The DE method that produced `de_table` (`de_res$method`).
#'   It decides the ranking statistic — see `mmc_gsea_rank_metric()`. Leave it
#'   NULL only when the method genuinely is not known: the generic `statistic`
#'   column is then not trusted, and the ranking falls to `logFC`.
#' @param n_perm,min_size,max_size,gsea_param,seed See
#'   `mmc_gsea_metaboanalyst()`; defaults are the pinned upstream values.
#' @param rank_metric How features sharing one m/z are merged (see
#'   `mmc_ec_scores()`).
#' @return `NULL` when GSEA cannot run (fgsea unavailable, no model, no ECs, no
#'   usable statistic, no pathway passing the size filter) and also when the
#'   engine itself fails — the two are reported apart, by a warning naming the
#'   cause and by a message naming the filter respectively, so an environment
#'   or engine failure is never read as an empty experiment. Otherwise a list:
#'   \describe{
#'     \item{table}{One row per tested pathway with `Pathway`,
#'       `Pathway size (model compounds)`, `Detected ECs`, `Tested size`, `ES`,
#'       `NES`, `P.Value`, `padj`, `Leading-edge EmpiricalCompounds`, sorted by
#'       ascending `P.Value`.}
#'     \item{ranks}{The signed EC score vector the ranking was built from.}
#'     \item{stats, tie_ranks}{The two vectors handed to the engine.}
#'     \item{metric, metric_label, de_method}{Which ranking statistic was
#'       chosen, why, and the DE method that decided it.}
#'     \item{nes_note}{`mmc_gsea_nes_note()`.}
#'     \item{params}{The exact engine settings used.}
#'     \item{deviations}{Character vector of departures from the pinned
#'       reference defaults; empty when there are none.}
#'     \item{reference}{The pinned MetaboAnalystR repo + commit, with
#'       `verified` / `unverified` naming which half of the pipeline the pin is
#'       evidence for: the GSEA calculation from the ranked EC inputs is checked
#'       against a reference generated by running upstream; the construction of
#'       those inputs is not (see `mmc_ec_scores()`).}
#'     \item{contrast, n_ec, n_pathways}{Provenance.}
#'   }
run_mummichog_gsea <- function(files, de_table, model, contrast = NULL,
                               de_method  = NULL,
                               n_perm     = .MMC_GSEA_DEFAULTS$n_perm,
                               min_size   = .MMC_GSEA_DEFAULTS$min_size,
                               max_size   = .MMC_GSEA_DEFAULTS$max_size,
                               gsea_param = .MMC_GSEA_DEFAULTS$gsea_param,
                               seed       = .MMC_GSEA_DEFAULTS$seed,
                               rank_metric = .MMC_GSEA_DEFAULTS$rank_metric) {
  # First, before the "cannot run here" branches below: an invalid parameter is
  # a caller error and must not be reported as "GSEA was not applicable".
  .mmc_gsea_check_param(gsea_param)
  # Validated and normalised once, here, so the value that runs is the value
  # reported: a result that said min_size = 0 while 1 was applied could not be
  # reproduced from its own provenance, and an NA bound would make a valid
  # experiment look like an empty one. The engine re-checks for direct callers.
  n_perm   <- .mmc_as_seed(n_perm, "n_perm")
  seed     <- .mmc_as_seed(seed, "seed")
  min_size <- max(.mmc_as_seed(min_size, "min_size"), 1L)
  max_size <- .mmc_gsea_check_max_size(max_size)
  if (n_perm < 1L) .mmc_stop("n_perm must be at least 1; got ", n_perm, ".")
  # Same reason, and match.arg() accepts abbreviations: resolved here, once, so
  # the computation, the deviation check and the provenance all see the name
  # that actually ran rather than whatever shorthand the caller typed.
  rank_metric <- match.arg(rank_metric, .MMC_GSEA_RANK_METRICS)

  if (!requireNamespace("fgsea", quietly = TRUE)) {
    message("mummichog GSEA: fgsea not available — skipping")
    return(NULL)
  }
  if (is.null(model) || length(model$pathways) == 0) {
    message("mummichog GSEA: no metabolic model pathways available — skipping")
    return(NULL)
  }
  rank <- mmc_gsea_rank_metric(de_table, de_method = de_method)
  if (is.null(rank)) {
    message("mummichog GSEA: no usable ranking statistic in the DE table — skipping")
    return(NULL)
  }

  ec_feat <- read_mummichog_ec_features(files)
  ec_cand <- read_mummichog_ec_candidates(files)
  if (nrow(ec_feat) == 0 || nrow(ec_cand) == 0) {
    message("mummichog GSEA: no EmpiricalCompound tables among the mummichog ",
            "outputs — skipping")
    return(NULL)
  }

  ec_scores <- mmc_ec_scores(ec_feat, rank$values, rank_metric = rank_metric)
  if (length(ec_scores) == 0) {
    message("mummichog GSEA: no EmpiricalCompound could be scored — skipping")
    return(NULL)
  }
  sets <- mmc_pathway_ec_sets(model$pathways, ec_cand, names(ec_scores))
  if (length(sets) == 0) {
    message("mummichog GSEA: no pathway has a detected EmpiricalCompound — skipping")
    return(NULL)
  }
  ranked <- mmc_gsea_ranked_inputs(ec_scores)

  res <- tryCatch(
    mmc_gsea_metaboanalyst(sets, ranked$stats, ranked$ranks, n_perm = n_perm,
                           min_size = min_size, max_size = max_size,
                           gsea_param = gsea_param, seed = seed),
    error = function(e) {
      warning("mummichog GSEA: engine failed: ", conditionMessage(e),
              call. = FALSE)
      NULL
    }
  )
  # An engine failure and an empty result are different outcomes and must not
  # share a diagnosis: the tryCatch above has already warned with the real
  # cause, and filtering may never have run at all. Reporting "no pathway
  # passed the size filter" for it would dress an environment or engine failure
  # up as a finding about the data.
  if (is.null(res)) return(NULL)
  if (nrow(res) == 0) {
    message("mummichog GSEA: no pathway passed the size filter")
    return(NULL)
  }

  # Three different quantities, all reported rather than conflated:
  #   * model compounds  — what the pathway contains
  #   * detected ECs     — what this dataset saw in it
  #   * tested size      — the tie-group index vector the engine scored, which
  #                        can exceed detected ECs when ECs share a score
  model_size <- vapply(res$pathway,
                       function(p) as.numeric(length(model$pathways[[p]])),
                       numeric(1), USE.NAMES = FALSE)
  detected <- vapply(res$pathway,
                     function(p) as.numeric(length(sets[[p]])),
                     numeric(1), USE.NAMES = FALSE)

  tbl <- data.frame(
    check.names = FALSE, stringsAsFactors = FALSE,
    "Pathway"                          = res$pathway,
    "Pathway size (model compounds)"   = model_size,
    "Detected ECs"                     = detected,
    "Tested size"                      = res$size,
    "ES"                               = round(res$ES, 4),
    "NES"                              = round(res$NES, 4),
    "P.Value"                          = res$pval,
    "padj"                             = res$padj,
    "Leading-edge EmpiricalCompounds"  = res$leadingEdge,
    # Reported so a defaulted 0 is never read as a measured enrichment score.
    # The flag is deliberately generic and the cause lives beside it, rather
    # than every fallback being labelled a tie.
    "ES defaulted by reference implementation" = res$es_defaulted,
    "ES fallback reason"                       = res$es_reason
  )
  tbl <- tbl[order(tbl[["P.Value"]], na.last = TRUE), , drop = FALSE]

  # Any departure from the pinned reference defaults is recorded, not hidden.
  deviations <- character(0)
  d <- .MMC_GSEA_DEFAULTS
  if (!identical(as.numeric(n_perm), as.numeric(d$n_perm))) {
    deviations <- c(deviations, sprintf(
      "n_perm = %s (MetaboAnalyst default %s)", n_perm, d$n_perm))
  }
  if (!identical(as.numeric(min_size), as.numeric(d$min_size))) {
    deviations <- c(deviations, sprintf(
      "min_size = %s (MetaboAnalyst default %s)", min_size, d$min_size))
  }
  if (!identical(as.numeric(max_size), as.numeric(d$max_size))) {
    deviations <- c(deviations, sprintf(
      "max_size = %s (MetaboAnalyst default Inf)", max_size))
  }
  # gsea_param is not listed: .mmc_gsea_check_param() admits only the reference
  # value, so it can never be a deviation.
  if (!identical(as.numeric(seed), as.numeric(d$seed))) {
    deviations <- c(deviations, sprintf(
      "seed = %s (MetaboAnalyst default %s)", seed, d$seed))
  }
  # How features sharing one m/z are merged changes every EC score, and so every
  # statistic downstream of it. Left out, a "min"/"max"/"median" run would
  # report an empty deviation list while differing from the reference at the
  # first step.
  if (!identical(rank_metric, d$rank_metric)) {
    deviations <- c(deviations, sprintf(
      "rank_metric = '%s' (MetaboAnalyst default '%s')",
      rank_metric, d$rank_metric))
  }
  # The single-permutable-pathway branch is OURS, not upstream's: the reference
  # leaves that loop to the BiocParallel worker's RNG, which is not
  # seed-deterministic, so there is nothing stable to reproduce. We seed it
  # instead -- better behaviour, but not validated parity, and the fixture's
  # six pathways never reach it. The engine reports whether it ran; a row count
  # no longer implies it, since unpermutable pathways are tested without being
  # permuted.
  if (isTRUE(attr(res, "mmc_single_pathway_rng"))) {
    deviations <- c(deviations, paste0(
      "one permutable pathway: the permutation loop is seeded here, where the ",
      "reference leaves it to a non-deterministic worker RNG — reproducible, ",
      "but this branch is not covered by the parity fixture"))
  }
  # Returning a row for a pathway that cannot be permuted is also ours: the
  # reference aborts on that input and produces no table at all, so this is a
  # departure even though it only applies where upstream yields nothing.
  n_unpermutable <- attr(res, "mmc_unpermutable")
  if (isTRUE(n_unpermutable > 0)) {
    deviations <- c(deviations, sprintf(
      paste0("%d pathway(s) tested but not permuted: no draw exists for them ",
             "(a tie-expanded size above the ranking, or a sole pathway ",
             "covering all of it), so they take an all-zero null (ES = 0, ",
             "p = 1) where the reference implementation aborts"),
      n_unpermutable))
  }
  # Same series as the validated fgsea build but a different patch: allowed,
  # and recorded. A different series never gets this far.
  fgsea_note <- .mmc_gsea_check_fgsea(warn = FALSE)
  if (!is.null(fgsea_note)) deviations <- c(deviations, fgsea_note)
  # Upstream aggregates its permutation tallies by data.table ROW, which is only
  # well defined for a single batch; we sum per pathway across batches instead.
  if (n_perm > .MMC_GSEA_GRANULARITY) {
    deviations <- c(deviations, sprintf(
      paste0("n_perm = %s exceeds upstream's batch granularity (%s); ",
             "permutation tallies are summed per pathway across batches, ",
             "which upstream's row-indexed aggregation does not do"),
      n_perm, .MMC_GSEA_GRANULARITY))
  }

  n_defaulted <- sum(res$es_defaulted)
  if (n_defaulted > 0) {
    reasons <- table(res$es_reason[res$es_defaulted])
    message("mummichog GSEA: ", n_defaulted, "/", nrow(res), " pathway(s) took ",
            "the reference implementation's ES = 0 fallback (",
            paste(sprintf("%s x%d", names(reasons), as.integer(reasons)),
                  collapse = "; "),
            "); flagged in the results table with the reason.")
  }
  message("mummichog GSEA: ", nrow(tbl), " pathways over ", length(ec_scores),
          " EmpiricalCompounds (", length(ranked$stats),
          " ranked positions), ranked by ", rank$label)

  list(
    table        = tbl,
    ranks        = ec_scores,
    stats        = ranked$stats,
    tie_ranks    = ranked$ranks,
    metric       = rank$metric,
    metric_label = rank$label,
    de_method    = rank$de_method,
    nes_note     = mmc_gsea_nes_note(),
    params       = list(n_perm = n_perm, min_size = min_size,
                        max_size = max_size, gsea_param = gsea_param,
                        seed = seed, rank_metric = rank_metric,
                        fgsea_version = as.character(
                          utils::packageVersion("fgsea"))),
    deviations   = deviations,
    # Scoped deliberately: the pin is evidence for the GSEA calculation, which
    # is checked against a reference generated by running upstream. It is not a
    # claim that the ranked EC inputs were built the way upstream builds them —
    # that part is matched by reading the source and is unverified (see
    # mmc_ec_scores()). A consumer stating "reproduces MetaboAnalystR" from this
    # field alone would be overstating what was checked.
    reference    = list(repo = .MMC_GSEA_REF_REPO,
                        commit = .MMC_GSEA_REF_COMMIT,
                        verified = "GSEA calculation from the ranked EC inputs",
                        unverified = paste0(
                          "construction of the ranked EC inputs, in particular ",
                          "the m/z merge in mmc_ec_scores(), which has no ",
                          "counterpart in the single-dataset upstream path and ",
                          "is covered by no parity fixture")),
    contrast     = contrast,
    n_ec         = length(ec_scores),
    n_positions  = length(ranked$stats),
    n_pathways   = nrow(tbl),
    n_es_defaulted = n_defaulted,
    es_fallback_reasons = if (n_defaulted == 0) character(0) else
      sort(unique(res$es_reason[res$es_defaulted]))
  )
}


# ==== plot ==================================================================

#' MetaboAnalyst-style GSEA summary scatter for peaks-to-pathways
#'
#' Reproduces the encoding of the pinned
#' `peaks_to_function.R::PlotPeaks2Paths()` GSEA branch:
#'
#' \itemize{
#'   \item x = `NES`
#'   \item y = `-log10(raw GSEA p-value)`
#'   \item colour = `NES` on a diverging scale centred at 0, in MetaboAnalyst's
#'     own colours (`#458B00` -> `#fffee0` -> `#7f0000`)
#'   \item point size = `sqrt(-log10(p))`, which is literally what MetaboAnalyst
#'     computes there (`radi.vec <- sqrt(abs(y))`, with `y` the -log10 p already
#'     on the vertical axis). It is therefore a redundant re-encoding of
#'     significance and carries no additional quantity — the legend says exactly
#'     that instead of inventing a meaning, and never exposes the upstream
#'     variable name.
#'   \item the most significant pathways labelled with `ggrepel`
#' }
#'
#' NES sign is kept only for parity with the reference implementation and is not
#' an interpretable direction — see `mmc_gsea_nes_note()`.
#'
#' Two additions to the reference, both non-encoding: the points are drawn as
#' outlined circles (`shape = 21`) so the near-white middle of the diverging
#' scale stays visible — matching the outlined bubbles used elsewhere in this
#' report — and the NES = 0 / p-cutoff guides are drawn, as in the other pathway
#' plots in this pipeline.
#'
#' @param gsea_df  The `table` from `run_mummichog_gsea()` (needs `Pathway`,
#'   `NES`, `P.Value`).
#' @param title    Plot title.
#' @param subtitle Plot subtitle (e.g. the contrast). Optional.
#' @param p_cutoff Significance cutoff for the dashed reference line.
#' @param label_top Number of most-significant pathways to label (needs
#'   `ggrepel`; silently unlabelled when it is unavailable).
#' @return A ggplot object, or `NULL` when there is nothing to plot (so the
#'   report section hides gracefully).
plot_mummichog_gsea_scatter <- function(gsea_df, title, subtitle = NULL,
                                        p_cutoff = 0.05, label_top = 8) {
  if (is.null(gsea_df) || !is.data.frame(gsea_df) || nrow(gsea_df) == 0) {
    return(NULL)
  }
  if (!all(c("Pathway", "NES", "P.Value") %in% names(gsea_df))) return(NULL)

  df <- data.frame(
    pathway = as.character(gsea_df$Pathway),
    NES     = suppressWarnings(as.numeric(gsea_df$NES)),
    p       = suppressWarnings(as.numeric(gsea_df[["P.Value"]])),
    stringsAsFactors = FALSE
  )
  df <- df[is.finite(df$NES) & is.finite(df$p), , drop = FALSE]
  if (nrow(df) == 0) return(NULL)

  # -log10 with a floor so an exact-zero p can't blow up the axis.
  df$neg_log10_p <- -log10(pmax(df$p, .Machine$double.eps))
  # MetaboAnalyst's radi.vec, verbatim: sqrt of the -log10 p on the y axis.
  df$significance_size <- sqrt(df$neg_log10_p)

  lim <- max(abs(df$NES), na.rm = TRUE)

  p <- ggplot2::ggplot(df, ggplot2::aes(x = .data$NES, y = .data$neg_log10_p)) +
    ggplot2::geom_vline(xintercept = 0, colour = "grey80") +
    ggplot2::geom_hline(yintercept = -log10(p_cutoff),
                        linetype = "dashed", colour = "grey50") +
    ggplot2::annotate("text", x = Inf, y = -log10(p_cutoff),
                      label = sprintf("p = %g", p_cutoff),
                      hjust = 1.05, vjust = -0.5, size = 3, colour = "grey40") +
    ggplot2::geom_point(
      ggplot2::aes(size = .data$significance_size, fill = .data$NES),
      shape = 21, colour = "grey25", stroke = 0.4, alpha = 0.9) +
    ggplot2::scale_fill_gradient2(
      low = "#458B00", mid = "#fffee0", high = "#7f0000", midpoint = 0,
      limits = c(-lim, lim), name = "NES") +
    # ASCII legend text on purpose: this label is rendered by the graphics
    # device on PNG/PDF export, where a non-ASCII glyph warns and degrades on a
    # minimal font setup.
    ggplot2::scale_size_continuous(
      range = c(1, 5), name = "Significance\nsqrt(-log10 p)") +
    ggplot2::labs(
      title    = title,
      subtitle = subtitle,
      x        = "NES  (normalized enrichment score)",
      y        = "-log10(GSEA p-value)") +
    ggplot2::theme_minimal() +
    ggplot2::theme(
      plot.title    = ggplot2::element_text(face = "bold", hjust = 0.5),
      plot.subtitle = ggplot2::element_text(hjust = 0.5))

  # Label the most significant pathways. ggrepel is optional across the repo, so
  # guard it and simply skip labels when it is not installed.
  if (label_top > 0 && requireNamespace("ggrepel", quietly = TRUE)) {
    lab_df <- df[order(df$p), , drop = FALSE]
    lab_df <- lab_df[seq_len(min(label_top, nrow(lab_df))), , drop = FALSE]
    p <- p + ggrepel::geom_text_repel(
      data = lab_df,
      ggplot2::aes(label = .data$pathway),
      size = 3, max.overlaps = Inf, box.padding = 0.5,
      min.segment.length = 0, seed = 42)
  }
  p
}
